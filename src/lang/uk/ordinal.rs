pub(super) fn ordinal(s: &str, form: usize) -> Option<String> {
    if s.is_empty() || s.starts_with('0') || !s.bytes().all(|x| x.is_ascii_digit()) {
        return None;
    }
    let n: usize = s.parse().ok()?;
    if n == 0 || n > 5999 {
        return None;
    }
    let th = n / 1000;
    let rem = n % 1000;
    if th != 0 && rem == 0 {
        let prefix = match th {
            1 => "",
            2 => "дво",
            3 => "трьох",
            4 => "чотирьох",
            5 => "п'яти",
            _ => return None,
        };
        let suffix = ["тисячний", "тисячна", "тисячне", "тисячного", "тисячному", "тисячні", "тисячних"][form];
        return Some(format!("{prefix}{suffix}"));
    }
    let mut words = Vec::new();
    if th != 0 {
        words.push(
            match th {
                1 => "тисяча",
                2 => "дві тисячі",
                3 => "три тисячі",
                4 => "чотири тисячі",
                5 => "п'ять тисяч",
                _ => return None,
            }
            .to_owned(),
        );
    }
    let h = rem / 100;
    let r = rem % 100;
    if h != 0 {
        if r == 0 {
            words.push(ORD_HUNDREDS[form][h - 1].to_owned());
        } else {
            words.push(number(&(h * 100).to_string(), Gender::Masculine, false)?);
        }
    }
    if r != 0 {
        if r < 10 {
            words.push(ORD_DIGITS[form][r].to_owned());
        } else if r < 20 {
            words.push(ORD_TEENS[form][r - 10].to_owned());
        } else if r % 10 == 0 {
            words.push(ORD_TIES[form][r / 10 - 2].to_owned());
        } else {
            words.push(number(&(r / 10 * 10).to_string(), Gender::Masculine, false)?);
            words.push(ORD_DIGITS[form][r % 10].to_owned());
        }
    }
    Some(words.join(" "))
}

pub(super) fn tagged(s: &str) -> Option<String> {
    let decades = [
        ("1990s", "дев'яності роки"),
        ("2000s", "двотисячні роки"),
        ("2010s", "дві тисячі десяті роки"),
        ("2020s", "двадцяті роки"),
        ("2030s", "тридцяті роки"),
    ];
    if let Some((_, v)) = decades.iter().find(|(k, _)| *k == s) {
        return Some((*v).to_owned());
    }
    let (num, suffix) = s.split_once(['-', '–'])?;
    let form = match suffix {
        "й" | "ий" => 0,
        "а" | "я" | "ша" => 1,
        "е" | "є" => 2,
        "го" | "ого" => 3,
        "му" | "ому" | "м" | "им" => 4,
        "ті" | "ні" | "і" | "ї" => 5,
        "х" | "их" => 6,
        _ => return None,
    };
    ordinal(num, form)
}
