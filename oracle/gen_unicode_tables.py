"""Freeze the CPython 3.12 (Unicode 15.0) character tables the Rust normalizer needs.

Run with CPython 3.12 (Unicode 15.0, the oracle's): `python3.12 oracle/gen_unicode_tables.py`.
Writes data/unicode/{isspace.txt,nd_ranges.txt,punct_ranges.txt,word_ranges.txt}
(word: Python `re` `\\w` for str patterns).
"""

import re
import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "data" / "unicode"


def ranges(pred):
    start = None
    for cp in range(0x110000):
        if pred(chr(cp)):
            if start is None:
                start = cp
        elif start is not None:
            yield start, cp - 1
            start = None
    if start is not None:
        yield start, 0x10FFFF


def write_ranges(name: str, header: str, pred) -> None:
    with open(OUT / name, "w") as f:
        f.write(header)
        for a, b in ranges(pred):
            f.write(f"{a:04X}\t{b:04X}\n")


def main() -> None:
    assert sys.version_info[:2] == (3, 12), sys.version
    assert unicodedata.unidata_version == "15.0.0", unicodedata.unidata_version
    OUT.mkdir(parents=True, exist_ok=True)
    header = (
        f"# generated by oracle/gen_unicode_tables.py, CPython {sys.version.split()[0]}, "
        f"Unicode {unicodedata.unidata_version}\n"
    )
    with open(OUT / "isspace.txt", "w") as f:
        f.write(header)
        for cp in range(0x110000):
            if chr(cp).isspace():
                f.write(f"{cp:04X}\n")
    write_ranges("nd_ranges.txt", header, lambda c: unicodedata.category(c) == "Nd")
    write_ranges("punct_ranges.txt", header, lambda c: unicodedata.category(c).startswith("P"))
    word = re.compile(r"\w")
    write_ranges("word_ranges.txt", header, lambda c: word.match(c) is not None)


if __name__ == "__main__":
    main()
